def broker_claims_scope():
    """Client scope of the citizen UI client: releases the brokered-login session notes as claims.

    The mapper omits a claim when its note is absent, so tokens from an email-code or
    passkey sign-in carry none of them. The notes are set only by the broker mappers below
    (server side, per session); a citizen cannot set or edit them.
    """
    def note_claim(name, note, claim):
        return mapper(name, "oidc-usersessionmodel-note-mapper", user_session_note=note, claim_name=claim,
                      jsonType_label="String", access_token_claim="true", id_token_claim="false",
                      introspection_token_claim="true")
    return scope(BROKER_SCOPE, "claims of a department-brokered sign-in (from the broker's session notes)", [
        note_claim("dept idp alias", *BROKER_ALIAS_NOTE),
        *[note_claim(out, note, out) for note, out in BROKER_CLAIMS],
    ], in_token_scope=False)


