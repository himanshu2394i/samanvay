"""Generates the DEV-ONLY realm exports in ./realms (kept so the JSON files
stay consistent). Run: python3 keycloak/gen_realms.py

Sign-in paths (asserted by KeycloakRealmExportIT):
  staff   - a passkey (user verification required) OR password + TOTP.
            No password-only path, including direct grants and password reset.
  citizen - signs up with name, email and a password (the email is the user name),
            then signs in with email + password, OR a passkey, OR a brokered
            sign-in through the MOCK department identity provider below
            (kc_idp_hint=dept-idp). No TOTP; direct grants are denied. (The
            email one-time-code authenticator in keycloak/email-otp is no longer
            part of the sign-in flow.)
  department (MOCK) - stands in for a department's own identity provider
            (a government IdP in a real deployment; none is integrated here).
            Password + TOTP, like staff. A citizen who signs in through it is
            brokered into the citizen realm, whose session then carries the
            department / local-id claims that DepartmentBrokerLinkProofProvider
            turns into a verified account link.

Nothing here is a real secret: staff dev users (dev-officer, dev-reviewer, dev-admin)
have *temporary* passwords that must be changed (and TOTP enrolled) on first login;
the citizen dev user dev-citizen has a plain dev password; department clients'
secrets are generated by Keycloak at import and never committed. Mail goes to the
dev/test Mailpit container.

Extra browser origins (e.g. a deployed HTTPS host) come from SAMANVAY_EXTRA_ORIGINS
(comma separated). The default is the origin of the AWS demo, so regenerating
reproduces the committed files instead of silently dropping it.

The one committed credential is BROKER_DEV_SECRET: the shared client secret
between the citizen realm's broker and the mock department realm's client. A
Keycloak identity provider cannot authenticate to its upstream without one, and
docker compose has no step to copy a generated secret across realms. It is a
labelled placeholder for two throwaway realms on a laptop - never reuse it, and
never point a broker with this value at a real identity provider.
"""
